/** Rarity tiers used by items and artefacts. */
enum class Rarity(val colorHex: Long, val weight: Double) {
    COMMON(0xBBBBBBFF, 46.0),
    UNCOMMON(0x57C25CFF, 28.0),
    RARE(0x4FA7DEFF, 16.0),
    EPIC(0xA96FD6FF, 8.0),
    LEGENDARY(0xF0B429FF, 2.0),
}

